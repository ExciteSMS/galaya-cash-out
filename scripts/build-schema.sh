#!/usr/bin/env bash
# Regenerates supabase/full_schema.sql from every migration, in order.
set -euo pipefail
cd "$(dirname "$0")/.."
out=supabase/full_schema.sql
{
  echo "-- GalaPesa: full database schema (generated by scripts/build-schema.sh)."
  echo "-- Run in the Supabase SQL Editor on a fresh project."
  for f in supabase/migrations/*.sql; do
    echo; echo "-- ===== $f ====="; cat "$f"; echo
  done
} > "$out"
echo "Wrote $out"
